-- 시간 변경 제안. 확정 참가자(호스트 제외)가 있는 모임의 시작 시각은 구성원 모두가 수락해야 바뀐다.
-- 모임 삭제(deleteWithChildren)가 DB CASCADE 에 기대므로 제안·응답은 ON DELETE CASCADE.
CREATE TABLE gathering_time_proposals
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gathering_id  BIGINT                   NOT NULL REFERENCES gatherings (id) ON DELETE CASCADE,
    proposer_id   BIGINT                   NOT NULL REFERENCES users (id),
    from_start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    to_start_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    status        VARCHAR(20)              NOT NULL,
    expires_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at   TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 한 모임에 진행 중인 제안은 하나
CREATE UNIQUE INDEX uk_gathering_time_proposals_pending ON gathering_time_proposals (gathering_id) WHERE status = 'PENDING';
-- 만료 작업이 찾는다
CREATE INDEX idx_gathering_time_proposals_pending_expires ON gathering_time_proposals (expires_at) WHERE status = 'PENDING';

-- 제안 시점의 구성원(호스트 포함 확정 참가자) 한 명당 한 행. 제안자는 처음부터 ACCEPTED.
CREATE TABLE gathering_time_proposal_votes
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id  BIGINT                   NOT NULL REFERENCES gathering_time_proposals (id) ON DELETE CASCADE,
    user_id      BIGINT                   NOT NULL REFERENCES users (id),
    decision     VARCHAR(20)              NOT NULL,
    responded_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_gathering_time_proposal_votes UNIQUE (proposal_id, user_id)
);
