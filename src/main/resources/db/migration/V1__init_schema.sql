-- BuddyGo 초기 스키마 (ERD v0.5 기준, 이름은 API 명세를 따름: gathering / buddy / review, 신청 레코드는 participation)
-- FK 삭제 동작은 ERD에 명시된 것만 지정하고 나머지는 기본값(NO ACTION)으로 둔다.

CREATE EXTENSION IF NOT EXISTS postgis;

-- ───────── 회원 ─────────

CREATE TABLE users
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(255)             NOT NULL,
    password_hash      VARCHAR(255),
    provider           VARCHAR(20)              NOT NULL DEFAULT 'LOCAL',
    provider_id        VARCHAR(255),
    name               VARCHAR(255)             NOT NULL,
    nickname           VARCHAR(255)             NOT NULL,
    gender             VARCHAR(20)              NOT NULL,
    manner_temperature NUMERIC(4, 1)            NOT NULL DEFAULT 36.5,
    push_enabled       BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_nickname UNIQUE (nickname),
    CONSTRAINT uk_users_provider UNIQUE (provider, provider_id)
);

CREATE TABLE device_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES users (id),
    fcm_token  VARCHAR(255)             NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_device_tokens_fcm_token UNIQUE (fcm_token)
);

CREATE INDEX idx_device_tokens_user ON device_tokens (user_id);

-- ───────── 모임 ─────────

CREATE TABLE places
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kakao_place_id VARCHAR(255),
    name           VARCHAR(255)             NOT NULL,
    road_address   VARCHAR(255),
    jibun_address  VARCHAR(255)             NOT NULL,
    region_code    CHAR(10)                 NOT NULL,
    location       GEOMETRY(Point, 4326)    NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_places_kakao_place_id UNIQUE (kakao_place_id)
);

CREATE INDEX idx_places_location ON places USING GIST (location);
CREATE INDEX idx_places_region_code ON places (region_code);
CREATE INDEX idx_places_jibun_address ON places (jibun_address);

CREATE TABLE gatherings
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id        BIGINT                   NOT NULL REFERENCES users (id),
    place_id       BIGINT                   NOT NULL REFERENCES places (id),
    sport          VARCHAR(20)              NOT NULL DEFAULT 'GYM',
    title          VARCHAR(255)             NOT NULL,
    description    VARCHAR(300),
    detail_address VARCHAR(255),
    start_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    capacity       SMALLINT                 NOT NULL,
    gender_rule    VARCHAR(20)              NOT NULL,
    status         VARCHAR(20)              NOT NULL,
    deleted_at     TIMESTAMP WITH TIME ZONE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_gatherings_period CHECK (end_at > start_at)
);

CREATE INDEX idx_gatherings_status_start_at ON gatherings (status, start_at);
CREATE INDEX idx_gatherings_status_end_at ON gatherings (status, end_at);
CREATE INDEX idx_gatherings_host ON gatherings (host_id);
CREATE INDEX idx_gatherings_place ON gatherings (place_id);

CREATE TABLE gathering_cancellations
(
    gathering_id BIGINT PRIMARY KEY REFERENCES gatherings (id),
    type         VARCHAR(20)              NOT NULL,
    reason       VARCHAR(100),
    canceled_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE gathering_likes
(
    user_id      BIGINT                   NOT NULL REFERENCES users (id),
    gathering_id BIGINT                   NOT NULL REFERENCES gatherings (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, gathering_id)
);

CREATE INDEX idx_gathering_likes_gathering ON gathering_likes (gathering_id);

-- 신청(PENDING)에서 확정·나가기까지 이어지는 참여 레코드. URL은 /applications
CREATE TABLE participations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gathering_id  BIGINT                   NOT NULL REFERENCES gatherings (id),
    user_id       BIGINT                   NOT NULL REFERENCES users (id),
    status        VARCHAR(20)              NOT NULL,
    reject_reason VARCHAR(30),
    message       VARCHAR(200),
    applied_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at    TIMESTAMP WITH TIME ZONE,
    left_at       TIMESTAMP WITH TIME ZONE
);

-- 진행 중인 신청·참여는 모임당 한 사람에 하나만. 거절·취소·나가기 후 재신청은 허용
CREATE UNIQUE INDEX uk_participations_active
    ON participations (gathering_id, user_id)
    WHERE status IN ('PENDING', 'CONFIRMED');
CREATE INDEX idx_participations_gathering_status ON participations (gathering_id, status);
CREATE INDEX idx_participations_user ON participations (user_id);

CREATE TABLE check_ins
(
    participation_id BIGINT PRIMARY KEY REFERENCES participations (id),
    attendance       VARCHAR(20) NOT NULL,
    checked_in_at    TIMESTAMP WITH TIME ZONE,
    distance_m       INTEGER
);

-- ───────── 종목: 헬스 ─────────

CREATE TABLE user_gym_records
(
    user_id      BIGINT                   NOT NULL REFERENCES users (id),
    body_part    VARCHAR(20)              NOT NULL,
    record_value NUMERIC,
    arm_level    VARCHAR(20),
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, body_part)
);

CREATE TABLE gathering_gym_parts
(
    gathering_id BIGINT      NOT NULL REFERENCES gatherings (id),
    body_part    VARCHAR(20) NOT NULL,
    record_value NUMERIC,
    arm_level    VARCHAR(20),
    PRIMARY KEY (gathering_id, body_part)
);

-- ───────── 공지 ─────────

CREATE TABLE notices
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gathering_id BIGINT                   NOT NULL REFERENCES gatherings (id),
    title        VARCHAR(255)             NOT NULL,
    content      VARCHAR(200)             NOT NULL,
    edited_at    TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_notices_gathering ON notices (gathering_id);

CREATE TABLE notice_comments
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id  BIGINT                   NOT NULL REFERENCES notices (id) ON DELETE CASCADE,
    author_id  BIGINT                   NOT NULL REFERENCES users (id),
    content    VARCHAR(200)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_notice_comments_notice ON notice_comments (notice_id);

-- ───────── 버디 ─────────

CREATE TABLE buddy_requests
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id    BIGINT                   NOT NULL REFERENCES users (id),
    receiver_id  BIGINT                   NOT NULL REFERENCES users (id),
    status       VARCHAR(20)              NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    responded_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_buddy_requests_not_self CHECK (sender_id <> receiver_id)
);

-- 같은 상대에게 대기 중인 신청은 하나만
CREATE UNIQUE INDEX uk_buddy_requests_pending
    ON buddy_requests (sender_id, receiver_id)
    WHERE status = 'PENDING';
CREATE INDEX idx_buddy_requests_receiver_status ON buddy_requests (receiver_id, status);

-- 수락 시 A→B, B→A 두 행
CREATE TABLE buddies
(
    user_id                  BIGINT                   NOT NULL REFERENCES users (id),
    buddy_id                 BIGINT                   NOT NULL REFERENCES users (id),
    notify_gathering_created BOOLEAN                  NOT NULL DEFAULT TRUE,
    notify_gathering_applied BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, buddy_id),
    CONSTRAINT ck_buddies_not_self CHECK (user_id <> buddy_id)
);

CREATE INDEX idx_buddies_buddy ON buddies (buddy_id);

-- ───────── 평가 ─────────

CREATE TABLE reviews
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gathering_id BIGINT                   NOT NULL REFERENCES gatherings (id),
    evaluator_id BIGINT                   NOT NULL REFERENCES users (id),
    target_id    BIGINT                   NOT NULL REFERENCES users (id),
    rating       VARCHAR(20)              NOT NULL,
    comment      VARCHAR(200),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reviews_gathering_evaluator_target UNIQUE (gathering_id, evaluator_id, target_id),
    CONSTRAINT ck_reviews_not_self CHECK (evaluator_id <> target_id)
);

CREATE INDEX idx_reviews_target ON reviews (target_id);

CREATE TABLE review_tags
(
    review_id BIGINT       NOT NULL REFERENCES reviews (id),
    tag       VARCHAR(255) NOT NULL,
    PRIMARY KEY (review_id, tag)
);

CREATE TABLE manner_temperature_logs
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                   NOT NULL REFERENCES users (id),
    delta        NUMERIC(4, 1)            NOT NULL,
    reason       VARCHAR(255)             NOT NULL,
    gathering_id BIGINT REFERENCES gatherings (id),
    review_id    BIGINT REFERENCES reviews (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_manner_temperature_logs_review UNIQUE (review_id)
);

CREATE INDEX idx_manner_temperature_logs_user ON manner_temperature_logs (user_id);

-- ───────── 알림 ─────────

CREATE TABLE notifications
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receiver_id      BIGINT                   NOT NULL REFERENCES users (id),
    actor_id         BIGINT REFERENCES users (id),
    type             VARCHAR(255)             NOT NULL,
    gathering_id     BIGINT REFERENCES gatherings (id),
    notice_id        BIGINT REFERENCES notices (id) ON DELETE SET NULL,
    buddy_request_id BIGINT REFERENCES buddy_requests (id) ON DELETE SET NULL,
    message          VARCHAR(255)             NOT NULL,
    read_at          TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_notifications_receiver_created ON notifications (receiver_id, created_at DESC);
-- 모두 읽음 처리, 안 읽은 개수 조회용
CREATE INDEX idx_notifications_receiver_unread ON notifications (receiver_id) WHERE read_at IS NULL;
